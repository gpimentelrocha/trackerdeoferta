import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { createStore } from '../src/store.js';
import { createCollector } from '../src/collector.js';
import { createApp } from '../src/app.js';
import { localDate } from '../src/time.js';
import { browserExecutable } from '../src/library.js';

test('navegador: cadastro, contagem, histórico, busca, edição e exclusão em desktop e celular', async () => {
  const store = createStore(':memory:');
  const collector = createCollector(store, async () => ({ count: 142, precision: 'approximate', label: '~142 resultados', ad_sample: {ads:[{id:'123456',start_date:localDate(new Date(Date.now()-20*86400000))},{id:'789012',start_date:localDate(new Date(Date.now()-40*86400000))}]} }));
  const server = createApp(store, collector).listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  const browser = await chromium.launch({ executablePath: browserExecutable(), args: ['--no-sandbox'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error' && /Content Security Policy|Refused/.test(message.text())) errors.push(message.text()); });
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.locator('#empty:not([hidden])').waitFor();
    await page.screenshot({ path: '/tmp/radar-empty-desktop.png', fullPage: true });
    await page.locator('#new-offer').click();
    await page.locator('#offer-form [name=name]').fill('Oferta <teste>');
    await page.locator('#offer-form [name=offer_type]').selectOption('info');
    await page.locator('#offer-form [name=niche]').fill('Renda extra');
    await page.locator('#offer-form [name=funnel]').selectOption('QUIZ + VSL');
    await page.locator('#offer-form [name=market]').selectOption('BR');
    assert.equal(await page.locator('#niche-options option[value=Prosperidade]').count(), 1);
    await page.locator('#offer-form [name=url]').fill('https://www.facebook.com/ads/library/?view_all_page_id=982937401569675&active_status=active&country=BR');
    await page.locator('#offer-form [type=submit]').click();
    await page.getByRole('heading', { name: 'Oferta <teste>', exact: true }).waitFor();
    await page.locator('.card-value strong').filter({ hasText: '142' }).waitFor();
    assert.equal(await page.locator('#metric-offers').innerText(), '1');
    assert.match(await page.locator('.insight-ages').innerText(), /40 dias/);
    assert.notEqual(await page.locator('.insight-score strong').innerText(), '—');
    await page.getByRole('button', {name:'Ver análise',exact:true}).click();
    await page.locator('#analysis-dialog[open]').waitFor();
    assert.match(await page.locator('#analysis-content').innerText(), /nota provisória/);
    assert.equal(await page.locator('#analysis-content tbody tr').count(), 2);
    assert.match(await page.locator('#analysis-content').innerText(), /não comprova vendas/);
    await page.locator('#close-analysis').click();
    assert.equal(await page.locator('#metric-ads').innerText(), '≈ 142');
    assert.equal(await page.locator('#daily-chart .daily-point').count(), 1);
    const offer = store.list()[0];
    const yesterday = localDate(new Date(Date.now() - 86400000));
    store.db.prepare('INSERT INTO snapshots(offer_id,day,count,precision,label,collected_at) VALUES(?,?,?,?,?,?)').run(offer.id, yesterday, 100, 'exact', '100 resultados', new Date(Date.now()-86400000).toISOString());
    await page.reload();
    await page.locator('#daily-chart .daily-point').nth(1).waitFor();
    await page.getByRole('button', { name: '7 dias', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: '7 dias', exact: true }).getAttribute('aria-pressed'), 'true');
    await page.locator('#daily-chart .daily-point').first().focus();
    await page.keyboard.press('Enter');
    assert.match(await page.locator('#chart-detail').innerText(), /100 anúncios/);
    assert.match(await page.locator('#chart-summary').innerText(), /\+42 anúncios/);
    await page.getByRole('button', { name: 'Tudo', exact: true }).click();
    await page.getByRole('button', { name: 'Ver histórico' }).click();
    assert.match(await page.locator('#history-body').innerText(), /142/);
    await page.locator('#close-history').click();
    await page.locator('#search').fill('inexistente');
    await page.locator('#no-results:not([hidden])').waitFor();
    await page.locator('#search').fill('');
    await page.getByRole('button', { name: 'Editar Oferta <teste>' }).click();
    await page.locator('#rename-form [name=name]').fill('Oferta editada');
    assert.equal(await page.locator('#rename-form [name=offer_type]').inputValue(), 'info');
    assert.equal(await page.locator('#rename-form [name=niche]').inputValue(), 'Renda extra');
    assert.equal(await page.locator('#rename-form [name=funnel]').inputValue(), 'QUIZ + VSL');
    assert.equal(await page.locator('#rename-form [name=market]').inputValue(), 'BR');
    await page.locator('#rename-form [name=market]').selectOption('LATAM');
    await page.locator('#rename-form [name=offer_type]').selectOption('drop');
    await page.locator('#rename-form [name=niche]').fill('Prosperidade');
    await page.locator('#rename-form [name=funnel]').selectOption('X1');
    await page.getByRole('button', { name: 'Salvar alterações' }).click();
    await page.getByRole('heading', { name: 'Oferta editada', exact: true }).waitFor();
    assert.match(await page.locator('.offer-tags').innerText(), /Drop/);
    assert.match(await page.locator('.offer-tags').innerText(), /Prosperidade/);
    assert.match(await page.locator('.offer-tags').innerText(), /X1/);
    assert.match(await page.locator('.offer-tags').innerText(), /LATAM/);
    await page.reload();
    await page.getByRole('heading', { name: 'Oferta editada', exact: true }).waitFor();
    await page.locator('#search').fill('LATAM');
    assert.equal(await page.locator('#offer-list .offer-card').count(), 1);
    await page.locator('#search').fill('');
    assert.equal(store.list()[0].history.length, 2);
    await page.screenshot({ path: '/tmp/radar-offers-desktop.png', fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.screenshot({ path: '/tmp/radar-mobile.png', fullPage: true });
    await page.getByRole('button', { name: 'Editar Oferta editada' }).click();
    assert.equal(await page.locator('#rename-form [name=market]').inputValue(), 'LATAM');
    assert.equal(await page.locator('#rename-form [name=funnel]').inputValue(), 'X1');
    assert.equal(await page.locator('#rename-dialog').evaluate(dialog => dialog.scrollWidth > dialog.clientWidth), false);
    await page.screenshot({ path: '/tmp/eletric-market-edit-mobile.png', fullPage: true });
    await page.locator('#close-rename').click();
    await page.getByRole('button', { name: 'Excluir Oferta editada' }).click();
    await page.locator('#confirm-delete').click();
    await page.locator('#empty:not([hidden])').waitFor();
    assert.equal(store.list().length, 0);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); await collector.close(); await new Promise(resolve => server.close(resolve)); store.close(); }
});
