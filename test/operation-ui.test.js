import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { createStore } from '../src/store.js';
import { createApp } from '../src/app.js';
import { browserExecutable } from '../src/library.js';

test('Minhas ofertas: produção completa, filtros, textos, links, edição, persistência e navegação móvel',async()=>{
  const store=createStore(':memory:');
  const tracked=store.create('Oferta monitorada','https://www.facebook.com/ads/library/?country=BR&view_all_page_id=123456');
  store.success(tracked.id,{count:15,precision:'exact',label:'15 resultados'});
  let collections=0;
  const server=createApp(store,{initial:()=>{collections++;},enqueue:()=>{},tick:()=>0}).listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  const browser=await chromium.launch({executablePath:browserExecutable(),args:['--no-sandbox']});
  try {
    const context=await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
    const page=await context.newPage();
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(`http://127.0.0.1:${server.address().port}`);
    await page.getByRole('heading',{name:'Oferta monitorada',exact:true}).waitFor();
    await page.getByRole('link',{name:/Minhas ofertas/}).click();
    await page.getByText('O próximo resultado começa aqui.',{exact:true}).waitFor();
    await page.getByRole('button',{name:'＋ Criar minha oferta',exact:true}).click();
    await page.getByLabel('Nome da minha oferta',{exact:true}).fill('Minha oferta de skincare');
    await page.locator('#my-offer-form [name=niche]').fill('Beleza');
    await page.getByLabel('Etapa da oferta').selectOption('production');
    await page.getByLabel('Notas e contexto',{exact:true}).fill('Público: mulheres interessadas em skincare.\nPromessa: uma rotina simples.');
    await page.getByRole('button',{name:'Salvar oferta',exact:true}).click();
    await page.getByRole('heading',{name:'Minha oferta de skincare',exact:true}).waitFor();
    for (const [kind,title] of [['copy','Copy de lançamento'],['copy','Vídeo UGC 01'],['copy','Ângulo de curiosidade']]) {
      await page.locator('[data-operation-action=new-material]').first().click();
      await page.getByLabel('Tipo de material',{exact:true}).selectOption(kind);
      await page.getByLabel('Título do material').fill(title);
      await page.getByLabel('Ângulo do criativo',{exact:true}).fill('Prova social');
      await page.getByLabel('Formato do criativo',{exact:true}).fill('UGC');
      await page.getByLabel('Status do material',{exact:true}).selectOption('ready');
      await page.getByLabel('Link do arquivo ou referência (opcional)',{exact:true}).fill('https://example.com/criativo?a=1&b=2');
      await page.getByLabel('Texto ou copy (opcional)',{exact:true}).fill('Gancho: você já passou por isso?\nCena 1: mostre a rotina.\n<script>window.injected=true</script>');
      assert.equal(await page.getByLabel('Roteiro (opcional)',{exact:true}).getAttribute('required'),null);
      if (title === 'Vídeo UGC 01') await page.getByLabel('Roteiro (opcional)',{exact:true}).fill('Roteiro do vídeo\nCena 1: depoimento\n<script>window.scriptInjected=true</script>');
      await page.getByRole('button',{name:'Salvar material',exact:true}).click();
      await page.getByRole('heading',{name:title,exact:true}).waitFor();
    }
    assert.equal(await page.locator('.material-card').count(),3);
    assert.equal(await page.locator('[data-material-filter=script]').count(),0);
    assert.equal(await page.locator('#my-material-form [name=kind] option[value=script]').count(),0);
    assert.equal(await page.locator('[data-material-filter=creative], [data-material-filter=angle]').count(),0);
    assert.deepEqual(await page.locator('#my-material-form [name=kind] option').evaluateAll(options=>options.map(option=>option.value)),['copy']);
    await page.locator('[data-material-filter=copy]').click();
    assert.equal(await page.locator('.material-card').count(),3);
    await page.getByLabel('Buscar materiais').fill('Vídeo UGC 01');
    assert.equal(await page.locator('.material-card').count(),1);
    assert.equal(await page.locator('.material-card h3').innerText(),'Vídeo UGC 01');
    await page.getByLabel('Buscar materiais').fill('inexistente');
    await page.getByRole('heading',{name:'Nenhum material corresponde à busca.'}).waitFor();
    await page.getByLabel('Buscar materiais').fill('Vídeo UGC 01');
    await page.getByRole('button',{name:'Ler material',exact:true}).click();
    assert.match(await page.locator('#my-read-content').innerText(),/Cena 1/);
    assert.match(await page.locator('#my-read-script').innerText(),/Roteiro do vídeo/);
    await page.locator('#my-read-script-copy').click();
    assert.match(await page.evaluate(()=>navigator.clipboard.readText()),/Roteiro do vídeo/);
    assert.equal(await page.locator('#my-read-link').getAttribute('href'),'https://example.com/criativo?a=1&b=2');
    await page.locator('#my-read-copy').click();
    assert.match(await page.evaluate(()=>navigator.clipboard.readText()),/Gancho/);
    await page.getByRole('button',{name:'Fechar leitura'}).click();
    await page.getByRole('button',{name:'Editar material',exact:true}).click();
    assert.match(await page.getByLabel('Roteiro (opcional)',{exact:true}).inputValue(),/Roteiro do vídeo/);
    await page.getByLabel('Roteiro (opcional)',{exact:true}).scrollIntoViewIfNeeded();
    await page.screenshot({path:'/tmp/eletric-optional-script.png',fullPage:false});
    await page.getByLabel('Status do material',{exact:true}).selectOption('winner');
    await page.getByLabel('Texto ou copy (opcional)',{exact:true}).fill('Copy vencedora\nNova versão');
    await page.route('**/api/my-offers/*/materials/*',route=>route.request().method()==='PATCH' ? route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'Falha temporária de teste.'})}) : route.continue());
    await page.getByRole('button',{name:'Salvar material',exact:true}).click();
    await page.locator('#my-material-error:not([hidden])').waitFor();
    assert.equal(await page.getByLabel('Texto ou copy (opcional)',{exact:true}).inputValue(),'Copy vencedora\nNova versão');
    await page.unroute('**/api/my-offers/*/materials/*');
    await page.getByRole('button',{name:'Salvar material',exact:true}).click();
    await page.locator('#my-material-dialog[open]').waitFor({state:'hidden'});
    await page.reload();
    await page.getByRole('heading',{name:'Vídeo UGC 01',exact:true}).waitFor();
    const creative=page.locator('.material-card').filter({has:page.getByRole('heading',{name:'Vídeo UGC 01',exact:true})});
    assert.match(await creative.innerText(),/Vencedor/);
    assert.match(await creative.innerText(),/Copy vencedora/);
    assert.equal(await page.evaluate(()=>window.injected),undefined);
    assert.equal(await page.evaluate(()=>window.scriptInjected),undefined);
    assert.match(await creative.innerText(),/Roteiro salvo/);
    await creative.getByRole('button',{name:'Editar material',exact:true}).click();
    assert.match(await page.getByLabel('Roteiro (opcional)',{exact:true}).inputValue(),/Roteiro do vídeo/);
    await page.getByLabel('Roteiro (opcional)',{exact:true}).fill('');
    await page.getByRole('button',{name:'Salvar material',exact:true}).click();
    await page.locator('#my-material-dialog[open]').waitFor({state:'hidden'});
    await creative.getByText('Roteiro salvo',{exact:true}).waitFor({state:'detached'});
    assert.doesNotMatch(await creative.innerText(),/Roteiro salvo/);
    assert.match(await creative.innerText(),/Copy vencedora/);
    await page.screenshot({path:'/tmp/eletric-operation-desktop.png',fullPage:true});
    await page.getByRole('link',{name:/Visão geral/}).click();
    await page.getByRole('heading',{name:'Oferta monitorada',exact:true}).waitFor();
    assert.equal(await page.locator('.card-value strong').innerText(),'15');
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('link',{name:/Minhas ofertas/}).click();
    await page.getByRole('link',{name:/Minha oferta de skincare/}).click();
    await page.locator('#my-tab-materials').click();
    await page.getByRole('heading',{name:'Vídeo UGC 01',exact:true}).waitFor();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:'/tmp/eletric-operation-mobile.png',fullPage:true});
    await page.getByRole('button',{name:'Excluir Vídeo UGC 01',exact:true}).click();
    await page.locator('#my-confirm-delete').click();
    await page.locator('#my-delete-dialog[open]').waitFor({state:'hidden'});
    await page.getByRole('heading',{name:'Vídeo UGC 01',exact:true}).waitFor({state:'detached'});
    assert.equal(await page.getByRole('heading',{name:'Vídeo UGC 01',exact:true}).count(),0);
    await page.getByRole('button',{name:'Excluir oferta',exact:true}).click();
    await page.locator('#my-confirm-delete').click();
    await page.getByText('O próximo resultado começa aqui.',{exact:true}).waitFor();
    assert.equal((await store.operation.list()).length,0);
    assert.equal(store.get(tracked.id).latest.count,15);
    assert.equal(collections,0);
    assert.deepEqual(errors,[]);
  } finally {await browser.close();await new Promise(resolve=>server.close(resolve));store.close();}
});
