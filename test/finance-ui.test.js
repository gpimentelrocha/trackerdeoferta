import test from 'node:test';
import assert from 'node:assert/strict';
import {chromium} from 'playwright-core';
import {createStore} from '../src/store.js';
import {createApp} from '../src/app.js';
import {browserExecutable} from '../src/library.js';
import {todayInBrazil} from '../public/finance-math.js';
const normalize=text=>text.replace(/\s/g,'');
test('financeiro no navegador: faturamento, custos gerais, ofertas, lucro, edição, períodos e layout móvel',async()=>{
  const store=createStore(':memory:');
  const a=await store.operation.create({name:'Skincare Essencial',niche:'Beleza',status:'scaling'});
  const b=await store.operation.create({name:'Método Fluência',niche:'Educação',status:'testing'});
  await store.operation.createMaterial(a.id,{title:'Copy original',content:'Minha copy preservada',script:'Meu roteiro opcional',angle:'Prova social',format:'UGC'});
  const server=createApp(store,{initial:()=>{throw new Error('Coleta indevida');}}).listen(0,'127.0.0.1');
  await new Promise(resolve=>server.once('listening',resolve));
  const browser=await chromium.launch({executablePath:browserExecutable(),args:['--no-sandbox']});
  try{
    const page=await browser.newPage({viewport:{width:1536,height:1100}}),errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    page.on('console',message=>{if(message.type()==='error'&&/Content Security Policy|Refused/.test(message.text()))errors.push(message.text());});
    await page.goto(`http://127.0.0.1:${server.address().port}/#minhas-ofertas`);
    await page.getByText('O próximo resultado começa aqui.',{exact:true}).waitFor();
    const entryForm=page.locator('#finance-entry-form');
    const waitMoney=(id,value)=>page.waitForFunction(({id,value})=>document.querySelector('#'+id).textContent.replace(/\s/g,'')===value,{id,value});
    const today=todayInBrazil(),lastMonth=new Date(today.slice(0,7)+'-01T12:00:00Z');lastMonth.setUTCDate(0);const oldDay=lastMonth.toISOString().slice(0,10);
    async function add(type,amount,offerId,description,category='ads',day=today){
      await page.locator(type==='revenue'?'#finance-add-revenue':'#finance-add-expense').click();
      await page.getByLabel('Valor em reais',{exact:true}).fill(amount);
      await entryForm.locator('[name=offer_id]').selectOption(offerId||'');
      await entryForm.locator('[name=description]').fill(description);
      await entryForm.locator('[name=day]').fill(day);
      if(type==='expense')await entryForm.locator('[name=category]').selectOption(category);
      await page.getByRole('button',{name:'Salvar lançamento',exact:true}).click();
      await page.locator('#finance-entry-dialog[open]').waitFor({state:'hidden'});
      await page.locator('#finance-summary[aria-busy=true]').waitFor({state:'detached'});
    }
    await add('revenue','1.000,00',a.id,'Vendas skincare');
    await add('expense','250,00',a.id,'Campanha principal','ads');
    await add('expense','100,00',null,'BM mensal','bm');
    await add('expense','30,00',a.id,'Proxy skincare','proxy');
    await add('expense','70,00',a.id,'Impostos skincare','tax');
    await add('revenue','500,00',b.id,'Vendas fluência');
    await add('revenue','200,00',a.id,'Vendas mês anterior','sales',oldDay);
    assert.equal(normalize(await page.locator('#finance-revenue').innerText()),'R$1.500,00');
    assert.equal(normalize(await page.locator('#finance-expense').innerText()),'R$450,00');
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$1.050,00');
    assert.equal(await page.locator('#finance-margin').innerText(),'70%');
    assert.equal(await page.locator('.finance-table tbody tr').count(),6);
    await page.getByLabel('Oferta do financeiro',{exact:true}).selectOption(a.id);
    await waitMoney('finance-profit','R$650,00');
    await page.locator('#finance-summary[aria-busy=true]').waitFor({state:'detached'});
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$650,00');
    assert.doesNotMatch(await page.locator('#finance-entries').innerText(),/BM mensal/);
    await page.getByRole('button',{name:'Editar lançamento Campanha principal',exact:true}).click();
    await page.getByLabel('Valor em reais',{exact:true}).fill('-2');
    await page.getByRole('button',{name:'Salvar lançamento',exact:true}).click();
    await page.locator('#finance-form-error:not([hidden])').waitFor();
    assert.equal(await page.getByLabel('Valor em reais',{exact:true}).inputValue(),'-2');
    await page.getByLabel('Valor em reais',{exact:true}).fill('300,00');
    await page.getByRole('button',{name:'Salvar lançamento',exact:true}).click();
    await page.locator('#finance-entry-dialog[open]').waitFor({state:'hidden'});
    await page.locator('#finance-summary[aria-busy=true]').waitFor({state:'detached'});
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$600,00');
    await page.getByRole('button',{name:'Excluir lançamento Proxy skincare',exact:true}).click();
    await page.getByRole('button',{name:'Excluir lançamento',exact:true}).click();
    await page.locator('#finance-delete-dialog[open]').waitFor({state:'hidden'});
    await page.locator('#finance-summary[aria-busy=true]').waitFor({state:'detached'});
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$630,00');
    await page.reload();await page.locator('#finance-revenue').filter({hasText:'1.000'}).waitFor();
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$630,00');
    await page.getByLabel('Período financeiro',{exact:true}).selectOption('custom');
    await page.getByLabel('Data inicial',{exact:true}).fill(oldDay);await page.getByLabel('Data final',{exact:true}).fill(oldDay);
    await page.locator('#finance-apply').click();await page.locator('#finance-summary[aria-busy=true]').waitFor({state:'detached'});
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$200,00');
    await page.getByLabel('Período financeiro',{exact:true}).selectOption('all');await page.locator('#finance-summary[aria-busy=true]').waitFor({state:'detached'});
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$830,00');
    await page.getByLabel('Oferta do financeiro',{exact:true}).selectOption('');await page.locator('#finance-summary[aria-busy=true]').waitFor({state:'detached'});
    await waitMoney('finance-profit','R$1.230,00');
    assert.equal(normalize(await page.locator('#finance-profit').innerText()),'R$1.230,00');
    assert.equal(await page.locator('#finance-chart svg').count(),1);
    assert.match(await page.locator('#finance-breakdown').innerText(),/BM/);
    await page.getByLabel('Buscar lançamentos',{exact:true}).fill('BM mensal');assert.equal(await page.locator('.finance-table tbody tr').count(),1);
    await page.getByLabel('Buscar lançamentos',{exact:true}).fill('');
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:'/tmp/eletric-finance-desktop.png',fullPage:true});
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.waitForFunction(()=>Number(document.querySelector('#finance-chart svg').getAttribute('viewBox').split(' ')[2])<400);
    await page.evaluate(()=>scrollTo(0,0));
    await page.screenshot({path:'/tmp/eletric-finance-mobile.png',fullPage:true});
    await page.getByLabel('Oferta do financeiro',{exact:true}).selectOption(a.id);
    await page.locator('#my-tab-materials').click();
    await page.getByRole('heading',{name:'Copy original',exact:true}).waitFor();
    await page.getByRole('button',{name:'Ler material',exact:true}).click();
    assert.equal(await page.locator('#my-read-script').innerText(),'Meu roteiro opcional');
    assert.equal(await page.locator('#my-read-content').innerText(),'Minha copy preservada');
    await page.getByRole('button',{name:'Fechar leitura',exact:true}).click();
    await page.locator('#my-tab-finance').click();
    await page.getByRole('link',{name:/Método Fluência/}).click();
    await waitMoney('finance-profit','R$500,00');
    await add('expense','800,00',b.id,'Campanha fluência','ads');
    await waitMoney('finance-profit','-R$300,00');
    assert.equal(await page.locator('#finance-margin').innerText(),'-60%');
    assert.equal(await page.locator('.finance-profit-card.is-negative').count(),1);
    assert.deepEqual(errors,[]);
  }finally{await browser.close();await new Promise(resolve=>server.close(resolve));store.close();}
});
